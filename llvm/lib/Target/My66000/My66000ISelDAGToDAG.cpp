static bool isFPshort(const APFloat FPVal2)
{
  APFloat FPVal = FPVal2;
  bool losesInfo;
  // The following copied from ConstantFP::isValueValidForType()
  // FPVal gets modified
  FPVal.convert(APFloat::IEEEsingle(), APFloat::rmNearestTiesToEven, &losesInfo);
LLVM_DEBUG(dbgs() << "\tAttempt shrink to f32: " << losesInfo << '\n');
  return !losesInfo;
}

static bool isFPhalf(const APFloat FPVal2)
{
  APFloat FPVal = FPVal2;
  bool losesInfo;
  FPVal.convert(APFloat::IEEEhalf(), APFloat::rmNearestTiesToEven, &losesInfo);
  return !losesInfo;
}

static bool isFPimm5(const APFloat FPVal)
{
  APSInt IVal(64, false);
  bool isExact;
  APFloat TVal = FPVal;
  TVal.add(TVal, APFloat::rmTowardZero);		// times 2
  TVal.convertToInteger(IVal, APFloat::rmTowardZero, &isExact);
  LLVM_DEBUG(dbgs() << "\tAttempt shrink to i5: " << isExact <<
      ", IVal=" << IVal << '\n');
  if (isExact) {
    int64_t imm = IVal.getExtValue();
    if (imm >= -31 && imm <= 31)
      return true;
  }
  return false;
}

static bool isFPpimm5(const APFloat FPVal)
{
  APSInt IVal(64, false);
  bool isExact;
  APFloat TVal = FPVal;
  TVal.add(TVal, APFloat::rmTowardZero);		// times 2
  TVal.convertToInteger(IVal, APFloat::rmTowardZero, &isExact);
  LLVM_DEBUG(dbgs() << "\tAttempt shrink to pi5: " << isExact <<
      ", IVal=" << IVal << '\n');
  if (isExact) {
    int64_t imm = IVal.getExtValue();
    if (imm >= 0 && imm <= 31)
      return true;
  }
  return false;
}


